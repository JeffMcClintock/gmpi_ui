// The sRGB transfer function, encode direction (IEC 61966-2-1), on [0,1].
// The same single definition as gmpi::drawing::linearToSRGB01 - every path
// that leaves the library's linear surfaces for an 8-bit consumer applies
// exactly this curve.
static inline float GMPI_linearToSRGB01(float c)
{
    c = c < 0.0f ? 0.0f : (c > 1.0f ? 1.0f : c);
    return (c <= 0.0031308f) ? c * 12.92f
                             : 1.055f * powf(c, 1.0f / 2.4f) - 0.055f;
}

// The character alignment box: ascent + descent, EXCLUDING lineGap.
// (OS/2 typo metrics when fsSelection bit 7 is set, Win metrics otherwise -
// see GmpiApiDrawing.h calcBodyHeight for why it is specifically not hhea.)
static inline float GMPI_calcBodyHeight(const GMPI_FontMetrics* fm)
{
    return fm->ascent + fm->descent;
}

