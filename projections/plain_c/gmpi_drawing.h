// Bit-encoded pixel format (gmpi::drawing::api::IBitmapPixels::PixelFormat):
//   [7:0]  bytes per pixel
//   [8]    1 = integer, 0 = float
//   [10:9] channel layout: 0=BGRA, 1=RGBA, 2=ARGB, 3=ABGR
//   [11]   1 = sRGB transfer function, 0 = linear
//
// Read these bits rather than assuming, and read ALL of them:
//   * bytes-per-pixel comes from bits [7:0], NOT from bytesPerRow / width.
//     Rows can be padded, so that division silently reports the wrong stride.
//   * channel layout comes from [10:9], NOT from #ifdef _WIN32. Backends do
//     not agree.
//   * the transfer function comes from [11] and means what it says.
//     Everything 8-bit and colour is sRGB-encoded; only ALPHA_8I coverage is
//     linear.
enum GMPI_PixelFormat
{
    // Linear float
    GMPI_PIXEL_FORMAT_RGBA_32F     = 16 | (1 << 9),                       // macOS 128bpp float
    GMPI_PIXEL_FORMAT_RGBA_16F     = 8 | (1 << 9),                        // Windows 64bpp half-float
    // Linear integer
    GMPI_PIXEL_FORMAT_RGBA_16I     = 8 | (1 << 8) | (1 << 9),             // macOS 64bpp uint16
    GMPI_PIXEL_FORMAT_ALPHA_8I     = 1 | (1 << 8),                        // 8bpp alpha mask
    // sRGB integer
    GMPI_PIXEL_FORMAT_BGRA_SRGB_8I = 4 | (1 << 8) | (1 << 11),            // Windows 32bpp sRGB
    GMPI_PIXEL_FORMAT_RGBA_SRGB_8I = 4 | (1 << 8) | (1 << 9) | (1 << 11), // macOS 32bpp sRGB
};

